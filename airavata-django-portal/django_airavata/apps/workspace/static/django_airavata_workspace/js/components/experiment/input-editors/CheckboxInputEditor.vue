<template>
  <!-- stop propagation of native input events so that they don't conflict with
  native input events generated by web component wrappers -->
  <div :id="id" class="flex flex-col gap-2">
    <Label
      v-for="option in checkboxOptions"
      :key="option.value"
      class="font-normal"
    >
      <Checkbox
        :model-value="selectedOptions.includes(option.value)"
        :disabled="readOnly"
        :aria-invalid="componentValidState === false"
        @update:model-value="(checked) => toggleOption(option.value, checked)"
      />
      {{ option.text }}
    </Label>
  </div>
</template>

<script>
import { InputEditorMixin } from "django-airavata-workspace-plugin-api";

const CONFIG_OPTION_TEXT_KEY = "text";
const CONFIG_OPTION_VALUE_KEY = "value";

export default {
  name: "checkbox-input-editor",
  mixins: [InputEditorMixin],
  props: {
    value: {
      type: String,
    },
    options: {
      type: Array,
      default: null,
    },
  },
  computed: {
    checkboxOptions: function () {
      // passed in options take precedence over options in input metadata
      const options = this.options || this.editorConfig.options || [];
      return options.map((option) => {
        return {
          text: option[CONFIG_OPTION_TEXT_KEY],
          value: option[CONFIG_OPTION_VALUE_KEY],
        };
      });
    },
    selectedOptions() {
      return this.data ? this.data.split(",") : [];
    },
  },
  methods: {
    selectionsChanged(values) {
      this.data = values && values.length > 0 ? values.join(",") : null;
      this.valueChanged();
    },
    toggleOption(value, checked) {
      const current = this.selectedOptions.slice();
      if (checked) {
        if (!current.includes(value)) {
          current.push(value);
        }
      } else {
        const index = current.indexOf(value);
        if (index !== -1) {
          current.splice(index, 1);
        }
      }
      // Preserve the option order defined by the editor config.
      const ordered = this.checkboxOptions
        .map((option) => option.value)
        .filter((optionValue) => current.includes(optionValue));
      this.selectionsChanged(ordered);
    },
  },
};
</script>

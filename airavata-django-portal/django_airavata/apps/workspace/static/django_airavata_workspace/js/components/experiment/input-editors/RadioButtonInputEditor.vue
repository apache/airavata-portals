<template>
  <!-- stop propagation of native input events so that they don't conflict with
  native input events generated by web component wrappers -->
  <div :id="id">
    <div
      v-for="opt in radioOptions"
      :key="opt.value"
      class="form-check"
    >
      <input
        class="form-check-input"
        type="radio"
        :id="id + '-' + opt.value"
        :name="id"
        :value="opt.value"
        :checked="data === opt.value"
        :disabled="readOnly"
        @change="onRadioChange(opt.value)"
        @change.stop
      />
      <label class="form-check-label" :for="id + '-' + opt.value">
        {{ opt.text }}
      </label>
    </div>
  </div>
</template>

<script>
import { InputEditorMixin } from "django-airavata-workspace-plugin-api";

const CONFIG_OPTION_TEXT_KEY = "text";
const CONFIG_OPTION_VALUE_KEY = "value";

export default {
  name: "radio-button-input-editor",
  mixins: [InputEditorMixin],
  props: {
    value: {
      type: String,
    },
    options: {
      type: Array,
    },
  },
  methods: {
    onRadioChange(value) {
      this.data = value;
      this.valueChanged();
    },
  },
  computed: {
    radioOptions: function () {
      // passed in options take precedence over options in input metadata
      const options = this.options || this.editorConfig.options || [];
      return options.map((option) => {
        return {
          text: option[CONFIG_OPTION_TEXT_KEY],
          value: option[CONFIG_OPTION_VALUE_KEY],
        };
      });
    },
  },
};
</script>

import BaseEnum from "./BaseEnum";

export default class ProcessState extends BaseEnum {

  get isFinished() {
    const finishedStates = [
      ProcessState.CANCELED,
      ProcessState.COMPLETED,
      ProcessState.FAILED,
    ];
    return finishedStates.indexOf(this) >= 0;
  }
}
